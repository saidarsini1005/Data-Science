/* Shared in-browser Python runner for experiment pages. */
(function () {
  "use strict";

  const CDN_URL = "https://cdn.jsdelivr.net/pyodide/v0.26.1/full/pyodide.js";
  const INDEX_URL = "https://cdn.jsdelivr.net/pyodide/v0.26.1/full/";
  const PACKAGES = ["numpy", "pandas", "scikit-learn", "matplotlib"];
  const PLOT_SETUP = [
    "import base64 as __portal_base64",
    "from io import BytesIO as __PortalBytesIO",
    "from js import _portal_emit_plot",
    "import matplotlib as __portal_matplotlib",
    "__portal_matplotlib.use('Agg')",
    "import matplotlib.pyplot as __portal_plt",
    "def __portal_show(*args, **kwargs):",
    "    for __portal_num in __portal_plt.get_fignums():",
    "        __portal_buffer = __PortalBytesIO()",
    "        __portal_plt.figure(__portal_num).savefig(__portal_buffer, format='png', bbox_inches='tight')",
    "        _portal_emit_plot(__portal_base64.b64encode(__portal_buffer.getvalue()).decode('ascii'))",
    "        __portal_plt.close(__portal_num)",
    "__portal_plt.show = __portal_show",
    "__portal_plt.close('all')"
  ].join("\n");

  let scriptPromise;
  let pyodidePromise;
  let pyodideInstance;
  let activeRunner;
  let isRunning = false;
  let readyToastShown = false;

  function escapeHtml(value) {
    return String(value == null ? "" : value).replace(/[&<>"']/g, function (char) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char];
    });
  }

  function runnerMarkup(code, choices) {
    const options = (choices || []).map(function (choice, index) {
      return '<option value="' + index + '">' + escapeHtml(choice.label) + "</option>";
    }).join("");
    const selector = choices && choices.length ?
      '<label class="runner-choice">Code sample<select class="runner-select" aria-label="Select sub-experiment code">' + options + "</select></label>" : "";
    return '<div class="python-runner">' +
      '<div class="runner-toolbar">' + selector + '<span class="runner-status" role="status">Pyodide loads on first run</span></div>' +
      '<label class="sr-only runner-editor-label">Editable Python code</label>' +
      '<textarea class="code-editor" spellcheck="false" autocapitalize="off" autocomplete="off" aria-label="Editable Python code">' + escapeHtml(code) + "</textarea>" +
      '<div class="runner-actions">' +
        '<button class="btn btn-primary btn-sm runner-run" type="button"><span class="runner-spinner" aria-hidden="true" hidden></span><span class="runner-run-label">&#9654; Run Code</span></button>' +
        '<button class="btn btn-ghost btn-sm runner-reset" type="button">Reset Code</button>' +
      "</div>" +
      '<pre class="terminal-output" tabindex="0" aria-label="Python console output" aria-live="polite"></pre>' +
      '<div class="runner-preview" aria-label="Matplotlib figure preview" hidden></div>' +
    "</div>";
  }

  function setStatus(text, ready) {
    document.querySelectorAll(".runner-status").forEach(function (status) {
      status.textContent = text;
      status.classList.toggle("is-ready", !!ready);
      status.classList.toggle("is-error", !ready && text === "Pyodide failed to load");
    });
  }

  function appendOutput(text) {
    if (!activeRunner || !text) return;
    activeRunner.output.textContent += text;
    activeRunner.output.scrollTop = activeRunner.output.scrollHeight;
  }

  function appendOutputLine(text) {
    appendOutput(text.endsWith("\n") ? text : text + "\n");
  }

  function loadScript() {
    if (window.loadPyodide) return Promise.resolve();
    if (scriptPromise) return scriptPromise;
    scriptPromise = new Promise(function (resolve, reject) {
      const script = document.createElement("script");
      script.src = CDN_URL;
      script.async = true;
      script.onload = resolve;
      script.onerror = function () { reject(new Error("Could not download Pyodide from the CDN.")); };
      document.head.appendChild(script);
    }).catch(function (error) {
      scriptPromise = null;
      throw error;
    });
    return scriptPromise;
  }

  async function ensurePyodide() {
    if (pyodideInstance) return pyodideInstance;
    if (!pyodidePromise) {
      pyodidePromise = (async function () {
        await loadScript();
        const runtime = await window.loadPyodide({ indexURL: INDEX_URL });
        runtime.setStdout({ batched: appendOutputLine });
        runtime.setStderr({ batched: appendOutputLine });
        window._portal_emit_plot = function (base64Image) {
          if (!activeRunner) return;
          const image = document.createElement("img");
          image.alt = "Matplotlib figure generated by the Python code";
          image.src = "data:image/png;base64," + base64Image;
          activeRunner.preview.appendChild(image);
          activeRunner.preview.hidden = false;
        };
        await runtime.loadPackage(PACKAGES);
        pyodideInstance = runtime;
        setStatus("Pyodide Environment Ready", true);
        if (!readyToastShown && typeof window.toast === "function") {
          window.toast("Pyodide Environment Ready");
          readyToastShown = true;
        }
        return runtime;
      })().catch(function (error) {
        pyodidePromise = null;
        throw error;
      });
    }
    return pyodidePromise;
  }

  function mountRunner(root, originalCode) {
    if (!root) return null;
    const editor = root.querySelector(".code-editor");
    const output = root.querySelector(".terminal-output");
    const preview = root.querySelector(".runner-preview");
    const runButton = root.querySelector(".runner-run");
    const resetButton = root.querySelector(".runner-reset");
    const spinner = root.querySelector(".runner-spinner");
    const runLabel = root.querySelector(".runner-run-label");
    let original = originalCode || editor.value;

    function setCode(code) {
      original = code || "";
      editor.value = original;
      output.textContent = "";
      output.classList.remove("has-error");
      preview.replaceChildren();
      preview.hidden = true;
    }

    resetButton.addEventListener("click", function () { setCode(original); });
    runButton.addEventListener("click", async function () {
      if (isRunning) return;
      isRunning = true;
      activeRunner = { output: output, preview: preview };
      output.textContent = "";
      output.classList.remove("has-error");
      preview.replaceChildren();
      preview.hidden = true;
      runButton.disabled = true;
      resetButton.disabled = true;
      runButton.setAttribute("aria-busy", "true");
      spinner.hidden = false;
      runLabel.textContent = "Loading Python...";

      try {
        const runtime = await ensurePyodide();
        runLabel.textContent = "Running...";
        await runtime.runPythonAsync(PLOT_SETUP + "\n" + editor.value);
        if (!output.textContent.trim()) output.textContent = "Code completed successfully with no text output.";
      } catch (error) {
        const traceback = error && error.message ? error.message : String(error);
        if (!output.textContent.includes(traceback)) {
          output.textContent += (output.textContent ? "\n" : "") + traceback;
        }
        output.classList.add("has-error");
        if (!pyodideInstance) setStatus("Pyodide failed to load", false);
      } finally {
        isRunning = false;
        activeRunner = null;
        runButton.disabled = false;
        resetButton.disabled = false;
        runButton.removeAttribute("aria-busy");
        spinner.hidden = true;
        runLabel.innerHTML = "&#9654; Run Code";
      }
    });

    const ready = root.querySelector(".runner-status");
    if (ready && pyodideInstance) {
      ready.textContent = "Pyodide Environment Ready";
      ready.classList.add("is-ready");
    }
    return { setCode: setCode };
  }

  window.pythonRunnerMarkup = runnerMarkup;
  window.mountPythonRunner = mountRunner;
})();